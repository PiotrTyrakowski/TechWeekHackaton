import assert from 'node:assert/strict';
import fs from 'node:fs';
import {compute} from './dist/engine.js';
import {mergeDemoRows} from './dist/demo-state.js';
import {graphData} from './dist/job-graph.js';
const {messages,events}=JSON.parse(fs.readFileSync(new URL('./dist/demo-small.json',import.meta.url)));
const base=compute(messages);
assert.deepEqual(base.totals,{pending:5450,agreed:5000,completed:0,paid:700});
assert.equal(base.jobs.length,5);assert.equal(base.tasks.length,3);assert.equal(base.gaps.length,1);
assert.equal(base.jobs.find(j=>j.id==='lipowa 5').customer,'Anna Nowak');
assert.deepEqual(compute([...messages,...messages]).totals,base.totals);
assert.deepEqual(compute([...messages].reverse()).totals,base.totals);
assert.throws(()=>compute([...messages,{...messages[0],raw_text:'collision'}]),/Conflicting/);
let rows=messages;const expected=[{pending:5450,agreed:5000,completed:0,paid:700},{pending:1150,agreed:9300,completed:0,paid:700},{pending:1150,agreed:5000,completed:4300,paid:700},{pending:1150,agreed:5000,completed:0,paid:5000}];
events.forEach((event,i)=>{rows=[...rows,event];const m=compute(rows,event.sent_at);assert.deepEqual(m.totals,expected[i]);assert.equal(m.gaps.length,0);});
assert.deepEqual(compute(rows,'2026-10-30T12:00:00+01:00').totals,expected[1]);
const event=text=>({source_id:'test',sent_at:'2026-10-30T12:00:00+01:00',raw_text:text,author_role:'owner',job_context:'lipowa 5'});
const changed=compute([...messages,event('New quote 4650 PLN without the cabin')]);
assert.equal(changed.jobs.find(j=>j.id==='lipowa 5').amount,4650);
assert.equal(changed.totals.pending,5800);
assert.equal(compute([...messages,{...event('I do not approve 4300 PLN'),author_role:'customer'}]).totals.agreed,5000);
assert.equal(compute([...messages,{...event('I confirm 3000 PLN'),author_role:'customer'}]).totals.agreed,5000);
console.log('PASS: initial states, replay, cutoff, dedupe, order independence, ID collision, new amount, negated and conflicting approvals.');

