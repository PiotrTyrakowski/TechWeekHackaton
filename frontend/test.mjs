assert.equal(expanded.jobs.length,20);assert.equal(expanded.tasks.length,13);assert.equal(expanded.gaps.length,4);
assert.deepEqual(expanded.totals,{pending:20150,agreed:26900,completed:3750,paid:9150});
assert.deepEqual(compute([...large.messages].reverse()).totals,expanded.totals);
assert.deepEqual(compute([...large.messages,...large.messages]).totals,expanded.totals);
const evolved=compute([...large.messages,...large.events],'2026-11-03T23:59:59+01:00');
assert.equal(evolved.gaps.length,3);assert.equal(evolved.totals.paid,13450);
assert.equal(evolved.jobs.find(j=>j.id==='lipowa 12').amount,2100);
assert.equal(evolved.jobs.find(j=>j.id==='lipowa 5').amount,4300);
console.log('PASS: expanded synthetic fixture, distinct addresses, non-payment promises, duplicates, order independence and replay.');
