assert.equal(migrated.length,210);assert.ok(migrated.includes(extra));assert.ok(migrated.includes(events[0]));
assert.equal(mergeDemoRows(migrated,large.messages).length,210);
const graph=graphData(expanded);assert.equal(graph.nodes.length,65);assert.equal(graph.edges.length,60);
assert.equal(new Set(graph.nodes.map(n=>n.id)).size,graph.nodes.length);
